-- Property Hub 0.14.9 · Rutas múltiples de apertura + correlación de comandos/eventos.
-- Un mismo punto de acceso puede abrirse por ZKBio API, por un relé Vimar hacia REX/Button,
-- por un relé en paralelo a la cerradura u otras rutas futuras. Property conserva auditoría unificada.

CREATE TABLE IF NOT EXISTS bh_access_execution_paths (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  installation_id BIGINT UNSIGNED NOT NULL,
  access_point_id BIGINT UNSIGNED NOT NULL,
  name VARCHAR(160) NOT NULL,
  path_type ENUM('vendor_api','relay_to_controller_input','parallel_relay','local_io','automation','manual','other') NOT NULL DEFAULT 'vendor_api',
  binding_id BIGINT UNSIGNED NULL,
  connector_instance_id BIGINT UNSIGNED NULL,
  external_object_type VARCHAR(50) NULL,
  external_id VARCHAR(190) NULL,
  topology_target ENUM('controller','rex_input','lock_parallel','lock_direct','other') NOT NULL DEFAULT 'controller',
  depends_on_controller TINYINT(1) NOT NULL DEFAULT 1,
  vendor_event_expected TINYINT(1) NOT NULL DEFAULT 0,
  priority SMALLINT NOT NULL DEFAULT 100,
  is_primary TINYINT(1) NOT NULL DEFAULT 0,
  enabled TINYINT(1) NOT NULL DEFAULT 1,
  pulse_ms INT UNSIGNED NULL,
  capabilities_json MEDIUMTEXT NULL,
  notes TEXT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  KEY ix_bh_access_path_access (installation_id,access_point_id,enabled,priority),
  KEY ix_bh_access_path_binding (binding_id),
  CONSTRAINT fk_bh_access_path_installation FOREIGN KEY (installation_id) REFERENCES bh_installations(id),
  CONSTRAINT fk_bh_access_path_access FOREIGN KEY (access_point_id) REFERENCES bh_access_points(id) ON DELETE CASCADE,
  CONSTRAINT fk_bh_access_path_binding FOREIGN KEY (binding_id) REFERENCES bh_asset_bindings(id) ON DELETE SET NULL,
  CONSTRAINT fk_bh_access_path_connector FOREIGN KEY (connector_instance_id) REFERENCES bh_connector_instances(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS bh_access_commands (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  installation_id BIGINT UNSIGNED NOT NULL,
  correlation_uuid CHAR(36) NOT NULL,
  access_point_id BIGINT UNSIGNED NOT NULL,
  execution_path_id BIGINT UNSIGNED NULL,
  actor_local_user_id BIGINT UNSIGNED NULL,
  actor_person_id BIGINT UNSIGNED NULL,
  property_id BIGINT UNSIGNED NULL,
  credential_type VARCHAR(40) NULL,
  source ENUM('property_app','admin','api','automation','reader','other') NOT NULL DEFAULT 'property_app',
  decision ENUM('allowed','denied','not_evaluated') NOT NULL DEFAULT 'not_evaluated',
  status ENUM('queued','sent','confirmed','failed','denied','timeout') NOT NULL DEFAULT 'queued',
  requested_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  sent_at DATETIME NULL,
  confirmed_at DATETIME NULL,
  details_json MEDIUMTEXT NULL,
  error_text TEXT NULL,
  UNIQUE KEY uq_bh_access_command_correlation (installation_id,correlation_uuid),
  KEY ix_bh_access_command_access_date (installation_id,access_point_id,requested_at),
  CONSTRAINT fk_bh_access_command_installation FOREIGN KEY (installation_id) REFERENCES bh_installations(id),
  CONSTRAINT fk_bh_access_command_access FOREIGN KEY (access_point_id) REFERENCES bh_access_points(id) ON DELETE CASCADE,
  CONSTRAINT fk_bh_access_command_path FOREIGN KEY (execution_path_id) REFERENCES bh_access_execution_paths(id) ON DELETE SET NULL,
  CONSTRAINT fk_bh_access_command_user FOREIGN KEY (actor_local_user_id) REFERENCES bh_local_users(id) ON DELETE SET NULL,
  CONSTRAINT fk_bh_access_command_person FOREIGN KEY (actor_person_id) REFERENCES bh_people(id) ON DELETE SET NULL,
  CONSTRAINT fk_bh_access_command_property FOREIGN KEY (property_id) REFERENCES bh_properties(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS bh_access_events (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  installation_id BIGINT UNSIGNED NOT NULL,
  access_point_id BIGINT UNSIGNED NULL,
  command_id BIGINT UNSIGNED NULL,
  connector_instance_id BIGINT UNSIGNED NULL,
  external_event_id VARCHAR(190) NULL,
  external_person_ref VARCHAR(190) NULL,
  person_id BIGINT UNSIGNED NULL,
  property_id BIGINT UNSIGNED NULL,
  event_time DATETIME NOT NULL,
  event_type VARCHAR(80) NOT NULL,
  credential_type VARCHAR(40) NULL,
  source_system VARCHAR(80) NOT NULL,
  result ENUM('success','denied','error','unknown') NOT NULL DEFAULT 'unknown',
  door_state VARCHAR(40) NULL,
  correlation_status ENUM('unmatched','matched_command','vendor_only','property_only') NOT NULL DEFAULT 'unmatched',
  raw_payload_json MEDIUMTEXT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_bh_access_event_external (installation_id,connector_instance_id,external_event_id),
  KEY ix_bh_access_event_access_date (installation_id,access_point_id,event_time),
  KEY ix_bh_access_event_person_date (installation_id,person_id,event_time),
  CONSTRAINT fk_bh_access_event_installation FOREIGN KEY (installation_id) REFERENCES bh_installations(id),
  CONSTRAINT fk_bh_access_event_access FOREIGN KEY (access_point_id) REFERENCES bh_access_points(id) ON DELETE SET NULL,
  CONSTRAINT fk_bh_access_event_command FOREIGN KEY (command_id) REFERENCES bh_access_commands(id) ON DELETE SET NULL,
  CONSTRAINT fk_bh_access_event_connector FOREIGN KEY (connector_instance_id) REFERENCES bh_connector_instances(id) ON DELETE SET NULL,
  CONSTRAINT fk_bh_access_event_person FOREIGN KEY (person_id) REFERENCES bh_people(id) ON DELETE SET NULL,
  CONSTRAINT fk_bh_access_event_property FOREIGN KEY (property_id) REFERENCES bh_properties(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
